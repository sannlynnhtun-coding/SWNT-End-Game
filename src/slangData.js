export function normalizeSlang(value) {
  return value.normalize('NFC').replace(/[\s\u200b-\u200d\ufeff]/g, '')
}
export function isSlangAnswer(puzzle, answer) {
  const normalized = normalizeSlang(answer)
  return [puzzle.word, ...puzzle.aliases].some(word => normalizeSlang(word) === normalized)
}
export function drawSlang(history = {}, previous = '') {
  const key = 'slang:burmese'
  let used = Array.isArray(history[key]) ? [...new Set(history[key])].filter(word => slangWords.some(item => item.word === word)) : []
  let pool = slangWords.filter(item => !used.includes(item.word))
  if (!pool.length) { used = []; pool = slangWords.filter(item => item.word !== previous) }
  const puzzle = pool[Math.floor(Math.random() * pool.length)]
  return { puzzle, history: { ...history, [key]: [...used, puzzle.word] } }
}
