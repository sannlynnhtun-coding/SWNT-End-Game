// History is explicit rather than a mutable module-level bag, so React StrictMode
// cannot consume extra words. Each category/difficulty completes its own cycle.
export function drawPuzzle(category, difficulty, history = {}, previous = '') {
  const pool = categories.find(item => item.id === category)?.words.filter(item => item.difficulty === difficulty)
  if (!pool?.length) throw new Error('Unknown category or difficulty')
  const key = `${category}:${difficulty}`
  const stored = Array.isArray(history[key]) ? history[key] : []
  let used = [...new Set(stored)].filter(word => pool.some(item => item.word === word))
  let remaining = pool.filter(item => !used.includes(item.word))
  if (!remaining.length) {
    used = []
    remaining = pool.filter(item => item.word !== previous)
  }
  const puzzle = remaining[Math.floor(Math.random() * remaining.length)]
  return { puzzle, history: { ...history, [key]: [...used, puzzle.word] } }
}
